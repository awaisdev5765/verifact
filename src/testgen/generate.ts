/**
 * Test generation: rules -> executable black-box test script.
 *
 * Output is a standalone Node script that runs against a live sandbox URL.
 * No framework magic — plain fetch + assertions, so the runner needs zero
 * per-repo test infra. Deterministic, auditable, fast.
 */
import { Rule, RuleResult, Verdict } from "../rules/schema.js";

const HEADER = `// GENERATED BY VERIFACT — do not edit.
// Every assertion here derives from a human statement of intent.
// Exports "results" for in-process execution; set VERIFACT_STANDALONE=1 to also print JSON.

const BASE = process.env.VERIFACT_BASE_URL ?? "http://127.0.0.1:3000";
const results = [];

async function call(method, path, body, headers = {}) {
  const res = await fetch(BASE + path, {
    method,
    headers: { "content-type": "application/json", ...headers },
    body: body ? JSON.stringify(body) : undefined,
    signal: AbortSignal.timeout(Number(process.env.VERIFACT_REQUEST_TIMEOUT_MS ?? 10000)),
  });
  let json = null;
  try { json = await res.json(); } catch {}
  return { status: res.status, json };
}

function record(id, verdict, detail, durationMs) {
  results.push({ id, verdict, detail, durationMs });
}

function get(obj, path) {
  return path.split(".").reduce((o, k) => (o == null ? o : o[k]), obj);
}

function compare(actual, expected, cmp) {
  switch (cmp) {
    case "gte": return actual >= expected;
    case "lte": return actual <= expected;
    case "neq": return actual !== expected;
    default:    return actual === expected;
  }
}
`;

const FOOTER = `
export { results };
if (process.env.VERIFACT_STANDALONE) {
  console.log(JSON.stringify(results));
}
`;

export function generateTestScript(rules: Rule[]): string {
  const parts = [HEADER];
  for (const rule of rules) {
    for (let i = 0; i < rule.assertions.length; i++) {
      const a = rule.assertions[i];
      const id = `${rule.id}#${i + 1}`;
      parts.push(genAssertion(id, rule.statement, a));
    }
  }
  parts.push(FOOTER);
  return parts.join("\n");
}

function genAssertion(id: string, statement: string, a: Rule["assertions"][number]): string {
  switch (a.kind) {
    case "api": {
      const cmp = a.comparator ?? "eq";
      return `
{
  const t0 = Date.now();
  try {
    const r = await call(${JSON.stringify(a.method)}, ${JSON.stringify(a.path)}, ${JSON.stringify(a.body ?? null)});
    let verdict = "VERIFIED"; let detail = "status " + r.status;
    if (r.status !== ${a.expectStatus ?? 200}) {
      verdict = "VIOLATED";
      detail = "expected status ${a.expectStatus ?? 200}, got " + r.status;
    }${
      a.expectField !== undefined
        ? `
    else {
      const v = get(r.json, ${JSON.stringify(a.expectField)});
      const ok = compare(v, ${JSON.stringify(a.expectValue)}, "${cmp}");
      verdict = ok ? "VERIFIED" : "VIOLATED";
      detail = ok ? detail : ${JSON.stringify(`${a.expectField} ${cmp} ${a.expectValue}`)} + " (got " + JSON.stringify(v) + ")";
    }`
        : ""
    }
    record(${JSON.stringify(id)}, verdict, detail, Date.now() - t0);
  } catch (e) {
    record(${JSON.stringify(id)}, "VIOLATED", "request failed: " + e.message, Date.now() - t0);
  }
}`;
    }
    case "error":
      return `
{
  const t0 = Date.now();
  const prevFault = process.env.VERIFACT_FAULT;
  try {
    process.env.VERIFACT_FAULT = ${JSON.stringify(a.inject)};
    const r = await call(${JSON.stringify(a.method)}, ${JSON.stringify(a.path)}, null);
    const ok = ${JSON.stringify(a.acceptableStatuses)}.includes(r.status);
    record(${JSON.stringify(id)}, ok ? "VERIFIED" : "VIOLATED",
      ok ? "fault handled with status " + r.status : "under fault ${a.inject} got status " + r.status + ", expected one of ${JSON.stringify(a.acceptableStatuses)}",
      Date.now() - t0);
  } catch (e) {
    record(${JSON.stringify(id)}, "VIOLATED", "request failed under fault: " + e.message, Date.now() - t0);
  } finally {
    // Restore the previous fault state — an injected fault must never leak
    // into later assertions (order-dependent false positives).
    if (prevFault === undefined) delete process.env.VERIFACT_FAULT;
    else process.env.VERIFACT_FAULT = prevFault;
  }
}`;
    case "invariant":
      // Invariants cannot be executed without an API mapping; honest verdict,
      // never a silent pass. The API-shaped rules around it carry the signal.
      return `
record(${JSON.stringify(id)}, "UNTESTABLE", ${JSON.stringify(`no API mapping for invariant: ${statement}`)}, 0);`;
  }
}

export function verdictTotals(results: RuleResult[]): Record<Verdict, number> {
  return {
    VERIFIED: results.filter((r) => r.verdict === "VERIFIED").length,
    VIOLATED: results.filter((r) => r.verdict === "VIOLATED").length,
    UNTESTABLE: results.filter((r) => r.verdict === "UNTESTABLE").length,
  };
}
